"""Чистое ядро per-user дедупа исходников (загрузили байт-в-байт то, что уже грузили).

Клиент считает отпечаток загружаемого файла (``<size>:<sha256-hex>``) и спрашивает сервер:
«я это уже грузил?». Если да — переиспользуем уже лежащий в R2 source (server-side копия), не
гоняя байты повторно. Решение делится на ДВА слоя (как transcript_cache): чистые функции здесь
(валидация отпечатка + выбор кандидата) под unit-тестом; I/O (поиск в БД, R2-копия) — в
``app/db.py`` / ``app/cloud_state.py`` / ``app/storage.py``.

БЕЗОПАСНОСТЬ: дедуп — СТРОГО per-user. Кросс-юзерное «уже существует» было бы оракулом
существования файла (IDOR-класс — команда только что закрыла такие утечки), поэтому кандидаты
приходят ТОЛЬКО из собственных прошлых джоб пользователя (I/O-слой фильтрует по ``user_id``).
"""

from __future__ import annotations

import re
from typing import Any

# ``<size-в-байтах>:<sha256-hex-lowercase>``. size — 1..20 цифр (int64-разрядность длины файла),
# хэш — РОВНО 64 lowercase-hex. Отпечаток приходит от КЛИЕНТА (сайд-канал) → строго валидируем,
# прежде чем пускать в запрос к БД (никакого мусора/инъекций в фильтр).
_FINGERPRINT_RE = re.compile(r"^\d{1,20}:[0-9a-f]{64}$")


def is_valid_fingerprint(fp: str) -> bool:
    """PURE. Отпечаток имеет вид ``<size>:<sha256-hex-lowercase>``?

    True ⇔ ``fp`` = 1..20 десятичных цифр, двоеточие, ровно 64 hex-символа в нижнем регистре.
    Отвергает: неверный hex, неверную длину хэша, заглавные буквы, отсутствие двоеточия, пустую
    строку, нецифровой size. Чистая проверка формата — доверять клиентскому вводу нельзя.
    """
    return bool(_FINGERPRINT_RE.match(fp))


def pick_duplicate_candidate(candidates: list[dict[str, Any]]) -> str | None:
    """PURE. Из СОБСТВЕННЫХ прошлых джоб юзера выбрать id «самой свежей» (или None, если пусто).

    ``candidates`` = ``[{"id": str, "created_at": <comparable>}, ...]`` — уже отфильтрованные по
    ``user_id`` + совпадающему отпечатку строки (I/O-слой). Выбираем самую свежую по ``created_at``
    (самый свежий source = максимальный шанс, что он ещё жив в R2 под 60-дневным ретеншном); при
    равном ``created_at`` тай-брейк по ``id`` — чтобы результат был ДЕТЕРМИНИРОВАННЫМ независимо от
    порядка строк из БД. ``[]`` → None.
    """
    if not candidates:
        return None
    best = max(candidates, key=lambda c: (c["created_at"], c["id"]))
    return str(best["id"])
