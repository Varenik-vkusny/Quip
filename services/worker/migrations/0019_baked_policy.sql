-- 0019_baked_policy.sql — политика рендера, ПОД КОТОРОЙ пайплайн запёк clips/<id>.mp4.
--
-- Применить в Supabase (Dashboard → SQL Editor → Run) ИЛИ через MCP apply_migration. Идемпотентна.
-- ⚠️ НАКАТИТЬ ДО ДЕПЛОЯ ВОРКЕРА: без колонки PostgREST-upsert job_artifacts.baked_policy вернёт
-- 400 (как было с 0016) — а пишет его КАЖДЫЙ прогон пайплайна.
--
-- ЗАЧЕМ (денежный баг, ревью 2026-07-14): чистый клип печётся пайплайном под тарифом владельца НА
-- МОМЕНТ ВЫПЕЧКИ (run.resolve_clip_render_policy → watermark / crf / preset), а полный рендер
-- /export/clean.mp4 резолвит тариф НА МОМЕНТ ЗАПРОСА. Fast-path отдаёт 302 на ЗАПЕЧЁННЫЙ объект →
-- если тариф между выпечкой и скачиванием СМЕНИЛСЯ, редирект молча отдаёт НЕ ТОТ файл:
--   • Free → Pro: пользователь ЗАПЛАТИЛ, а скачивает клип С ВОТЕРМАРКОЙ (и с free-crf/preset);
--   • Pro → Free: скачивает клип БЕЗ вотермарки — обход монетизации.
-- Ни одна сторона не видит ошибки: файл отдан, он просто ЧУЖОЙ. Колонка хранит отпечаток политики
-- выпечки (run.render_policy_fingerprint: {watermark, max_resolution, video_crf, video_preset});
-- эндпоинт сверяет его с текущей политикой владельца и при РАСХОЖДЕНИИ (а также при ОТСУТСТВИИ —
-- все джобы до этой миграции) идёт честным полным рендером. Fail-safe по построению: худший
-- случай = сегодняшняя медленная скачка, НИКОГДА = чужой файл.
--
-- Джоб-уровневая (не per-clip): все клипы одного прогона печёт один фан-аут одного владельца в
-- один момент → одна политика. Пишет КООРДИНАТОР (run._render_all_clips), а не клип-контейнеры →
-- нет гонки read-modify-write между параллельными контейнерами фан-аута (в отличие от
-- reframe_regions, которым нужен был atomic-merge RPC 0013). Локальный dev — колонка не нужна
-- (db.put_job_artifact no-op на SQLite → политика неизвестна → полный рендер, что локально дёшево).

alter table public.job_artifacts add column if not exists baked_policy jsonb;
